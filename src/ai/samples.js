export function normalizeSubject(subject = '') {
  const value = String(subject).toLowerCase()
  if (value.includes('数学') || value.includes('math')) return '数学'
  if (value.includes('语文') || value.includes('chinese')) return '语文'
  if (value.includes('英语') || value.includes('english')) return '英语'
  return ''
}

const norm = (v) => String(v ?? '').toLowerCase().replace(/[\s_＿，。；：、！？"'“”‘’（）()\[\]{}<>,.;:!?＝]/g, '').replace(/[×*]/g, '').replace(/^(古诗)?(默写|解方程|修改病句)/, '')

// 严格匹配：只有题目与预置样例基本一致时才命中，避免把别的题错配到样例答案
export function findSample({ question = '' } = {}) {
  const q = norm(question)
  if (!q) return null
  for (const sample of samples) {
    const s = norm(sample.question)
    if (q === s || (q.length >= 8 && (s.includes(q) || q.includes(s)))) return sample
  }
  return null
}

